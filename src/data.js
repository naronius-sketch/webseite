export function formatPrice(property) {
  const formatted = new Intl.NumberFormat('en-KE', {
    maximumFractionDigits: 0,
  }).format(property.price);
  return `KSh ${formatted}${property.purpose === 'rent' ? ' / month' : ''}`;
}
